export function draftUserMessage(p: { today: string; customer: string; body: string; triageSummary: string; orderBlock: string }) {
  return `[오늘 날짜] ${p.today}
[고객명] ${p.customer}
[분류 요약] ${p.triageSummary}
[주문 정보]
${p.orderBlock}

[고객 문의]
${p.body}`;
}

